const TABS: Tab[] = [
  { href: "/", label: "Home", icon: HomeIcon },
  { href: "/month", label: "Month", icon: MonthIcon },
  { href: "/history", label: "History", icon: HistoryIcon },
  { href: "/settings", label: "Settings", icon: SettingsIcon },
];

export default function TabBar() {
  const pathname = usePathname();

  return (
    <nav
      aria-label="Primary"
      className="sticky bottom-0 z-10 w-full border-t border-border bg-surface/95 backdrop-blur supports-[backdrop-filter]:bg-surface/80"
    >
      <div className="mx-auto flex max-w-md items-stretch justify-between px-2 pb-[env(safe-area-inset-bottom)]">
        {TABS.map(({ href, label, icon: Icon }) => {
          const active = href === "/" ? pathname === "/" : pathname.startsWith(href);
          return (
            <Link
              key={href}
              href={href}
              aria-current={active ? "page" : undefined}
              className="flex flex-1 flex-col items-center justify-center gap-1 py-2.5 text-[11px] font-medium"
            >
              <Icon
                className={`h-6 w-6 ${active ? "text-brand" : "text-muted"}`}
              />
              <span className={active ? "text-brand" : "text-muted"}>
                {label}
              </span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
